//! Writes `src/schema.txt`, the GraphQL schema every resolver checks against, from the pinned GHES 3.22 SDL
//! (`design/SHARED.md`, `graphql`: "Schema generated from GHES 3.22 SDL, so `__type` probes match"; `gh/README.md`).
//!
//! Usage: `cargo run -p graftyard-api --example gen_schema -- <schema.docs-enterprise.graphql> > crates/api/src/schema.txt`
//!
//! One line per type, then one per field or enum value, in SDL order:
//! `T <name> <S|O|I|U|E|N> <interfaces or union members, comma-separated, or ->`,
//! `F <name> <type> <0|1 deprecated> <args as name:type, comma-separated, or ->`, and `V <name> <0|1 deprecated>`.
//! Input objects list their input fields as `F` lines with no args.

use graphql_parser::schema::{Definition, Directive, InputValue, Type, TypeDefinition, parse_schema};
use sha2::{Digest, Sha256};

fn ty(t: &Type<'_, String>) -> String {
    match t {
        Type::NamedType(n) => n.clone(),
        Type::ListType(t) => format!("[{}]", ty(t)),
        Type::NonNullType(t) => format!("{}!", ty(t)),
    }
}

fn deprecated(d: &[Directive<'_, String>]) -> u8 {
    u8::from(d.iter().any(|d| d.name == "deprecated"))
}

fn list(v: &[String]) -> String {
    if v.is_empty() { "-".into() } else { v.join(",") }
}

fn args(a: &[InputValue<'_, String>]) -> String {
    list(&a.iter().map(|a| format!("{}:{}", a.name, ty(&a.value_type))).collect::<Vec<_>>())
}

fn main() {
    let path = std::env::args().nth(1).expect("usage: gen_schema <schema.docs-enterprise.graphql>");
    let sdl = std::fs::read_to_string(&path).expect("read the SDL");
    let doc = parse_schema::<String>(&sdl).expect("parse the SDL");
    let mut out = format!("# generated by examples/gen_schema.rs from sha256 {:x}\n", Sha256::digest(sdl.as_bytes()));
    for d in &doc.definitions {
        let Definition::TypeDefinition(t) = d else { continue };
        match t {
            TypeDefinition::Scalar(s) => out += &format!("T {} S -\n", s.name),
            TypeDefinition::Object(o) => {
                out += &format!("T {} O {}\n", o.name, list(&o.implements_interfaces));
                for f in &o.fields {
                    out += &format!(
                        "F {} {} {} {}\n",
                        f.name,
                        ty(&f.field_type),
                        deprecated(&f.directives),
                        args(&f.arguments)
                    );
                }
            }
            TypeDefinition::Interface(i) => {
                out += &format!("T {} I {}\n", i.name, list(&i.implements_interfaces));
                for f in &i.fields {
                    out += &format!(
                        "F {} {} {} {}\n",
                        f.name,
                        ty(&f.field_type),
                        deprecated(&f.directives),
                        args(&f.arguments)
                    );
                }
            }
            TypeDefinition::Union(u) => out += &format!("T {} U {}\n", u.name, list(&u.types)),
            TypeDefinition::Enum(e) => {
                out += &format!("T {} E -\n", e.name);
                for v in &e.values {
                    out += &format!("V {} {}\n", v.name, deprecated(&v.directives));
                }
            }
            TypeDefinition::InputObject(i) => {
                out += &format!("T {} N -\n", i.name);
                for f in &i.fields {
                    out += &format!("F {} {} {} -\n", f.name, ty(&f.value_type), deprecated(&f.directives));
                }
            }
        }
    }
    print!("{out}");
}
