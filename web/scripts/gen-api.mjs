// web/scripts/gen-api.mjs writes src/api/ghes.d.ts from the whole pinned GHES 3.22 REST description, so the client and
// the mock handlers type every GHES operation. tsrs checks the 5.7 MB result as fast as the pruned one (measured 459 ms
// against 447 ms), so there is no list of operations to keep in step.
// Run: npm run gen:api. Set GHES_JSON to a local copy of the description to skip the download.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

// The commit crates/api/gh/README.md pins.
const COMMIT = "755ee33b4a81d51f6f07a902cce26cbec3b822f2";
const URL = `https://raw.githubusercontent.com/github/rest-api-description/${COMMIT}/descriptions/ghes-3.22/ghes-3.22.json`;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cache = join(root, "node_modules", ".cache", `ghes-3.22-${COMMIT}.json`);
const out = join(root, "src", "api", "ghes.d.ts");

async function loadDescription() {
  if (process.env.GHES_JSON) return readFileSync(process.env.GHES_JSON, "utf8");
  if (existsSync(cache)) return readFileSync(cache, "utf8");
  console.log(`downloading ${URL}`);
  const res = await fetch(URL);
  if (!res.ok) throw new Error(`download failed: ${res.status} ${res.statusText}`);
  const text = await res.text();
  mkdirSync(dirname(cache), { recursive: true });
  writeFileSync(cache, text);
  return text;
}

// Examples are documentation only and drag in large example components.
function stripExamples(node) {
  if (Array.isArray(node)) return node.map(stripExamples);
  if (node === null || typeof node !== "object") return node;
  const copy = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "examples" || k === "example") continue;
    copy[k] = stripExamples(v);
  }
  return copy;
}

const spec = stripExamples(JSON.parse(await loadDescription()));
const ast = await openapiTS(spec);
const header = `// Generated by web/scripts/gen-api.mjs from GHES 3.22 (rest-api-description ${COMMIT}). Do not edit.\n`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, header + astToString(ast));
console.log(`wrote ${out}: ${Object.keys(spec.paths).length} paths`);
